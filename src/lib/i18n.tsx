interface I18nContextType {
  language: SupportedLanguage;
  setLanguage: (lang: SupportedLanguage) => void;
  adminLangMode: 'en' | 'preferred';
  setAdminLangMode: (mode: 'en' | 'preferred') => void;
  effectiveLang: SupportedLanguage;
  t: (key: string) => string;
  translateCategory: (cat: string) => string;
  translateDepartment: (dept: string) => string;
  translateStatus: (status: string) => string;
  translatePriority: (priority: string) => string;
  formatDate: (date: string | Date | null | undefined) => string;
  formatNumber: (num: number | string | null | undefined) => string;
}

const I18nContext = createContext<I18nContextType>({
  language: 'en',
  setLanguage: () => {},
  adminLangMode: 'en',
  setAdminLangMode: () => {},
  effectiveLang: 'en',
  t: (key: string) => key,
  translateCategory: (cat: string) => cat,
  translateDepartment: (dept: string) => dept,
  translateStatus: (st: string) => st,
  translatePriority: (pr: string) => pr,
  formatDate: () => '',
  formatNumber: (n: any) => String(n ?? ''),
});

export function I18nProvider({
  children,
  initialLang = 'en',
}: {
  children: React.ReactNode;
  initialLang?: SupportedLanguage;
}) {
  const [language, setLanguageState] = useState<SupportedLanguage>(initialLang);
  const [adminLangMode, setAdminLangModeState] = useState<'en' | 'preferred'>('en');

  useEffect(() => {
    let savedLang: string | null = null;
    try {
      const match = document.cookie.match(/(^|;)\s*civic_lang\s*=\s*([^;]+)/);
      savedLang = match ? decodeURIComponent(match[2].trim()) : localStorage.getItem('civicresolve_lang');
    } catch {}

    if (savedLang && translations[savedLang as SupportedLanguage]) {
      setLanguageState(savedLang as SupportedLanguage);
    }
    const savedAdminMode = localStorage.getItem('civicresolve_admin_lang_mode') as 'en' | 'preferred';
    if (savedAdminMode) {
      setAdminLangModeState(savedAdminMode);
    }
  }, []);

  const setLanguage = (lang: SupportedLanguage) => {
    setLanguageState(lang);
    localStorage.setItem('civicresolve_lang', lang);
    document.cookie = `civic_lang=${lang}; path=/; max-age=31536000`;
  };

  const setAdminLangMode = (mode: 'en' | 'preferred') => {
    setAdminLangModeState(mode);
    localStorage.setItem('civicresolve_admin_lang_mode', mode);
  };

  const effectiveLang: SupportedLanguage = language;

  const t = (key: string): string => {
    return translations[language]?.[key] || translations.en[key] || key;
  };

  const translateCategory = (cat: string): string => {
    if (!cat) return '';
    return CATEGORY_TRANSLATIONS[language]?.[cat] || cat;
  };

  const translateDepartment = (dept: string): string => {
    if (!dept) return '';
    return DEPARTMENT_TRANSLATIONS[language]?.[dept] || dept;
  };

  const translateStatus = (status: string): string => {
    if (!status) return '';
    const norm = status.toUpperCase();
    return STATUS_TRANSLATIONS[language]?.[norm] || status;
  };

  const translatePriority = (priority: string): string => {
    if (!priority) return '';
    const norm = priority.toUpperCase();
    return PRIORITY_TRANSLATIONS[language]?.[norm] || priority;
  };

  const formatDate = (dateInput: string | Date | null | undefined): string => {
    if (!dateInput) return '';
    const d = new Date(dateInput);
    if (isNaN(d.getTime())) return '';

    const localeMap: Record<SupportedLanguage, string> = {
      en: 'en-IN',
      hi: 'hi-IN',
      ta: 'ta-IN',
      te: 'te-IN',
      kn: 'kn-IN',
      ml: 'ml-IN',
      mr: 'mr-IN',
      bn: 'bn-IN',
      gu: 'gu-IN',
      pa: 'pa-IN',
      ur: 'ur-PK',
    };

    return new Intl.DateTimeFormat(localeMap[language] || 'en-IN', {
      day: 'numeric',
      month: 'short',
      year: 'numeric',
      hour: '2-digit',
      minute: '2-digit',
    }).format(d);
  };

  const formatNumber = (num: number | string | null | undefined): string => {
    if (num === null || num === undefined) return '';
    const n = typeof num === 'string' ? parseFloat(num) : num;
    if (isNaN(n)) return String(num);

    const localeMap: Record<SupportedLanguage, string> = {
      en: 'en-IN',
      hi: 'hi-IN',
      ta: 'ta-IN',
      te: 'te-IN',
      kn: 'kn-IN',
      ml: 'ml-IN',
      mr: 'mr-IN',
      bn: 'bn-IN',
      gu: 'gu-IN',
      pa: 'pa-IN',
      ur: 'ur-PK',
    };
    return new Intl.NumberFormat(localeMap[language] || 'en-IN').format(n);
  };

  return (
    <I18nContext.Provider
      value={{
        language,
        setLanguage,
        adminLangMode,
        setAdminLangMode,
        effectiveLang,
        t,
        translateCategory,
        translateDepartment,
        translateStatus,
        translatePriority,
        formatDate,
        formatNumber,
      }}
    >
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}
